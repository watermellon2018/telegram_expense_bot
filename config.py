# ── Защита от дубликатов расходов в совместных проектах (feature_110) ──────────
#
# Расход считается потенциальным дубликатом, если в том же проекте другой участник
# недавно добавил расход с той же датой, категорией и близкой суммой.
# Проверка детерминированная (без ML/LLM/внешних API).

# Временное окно: насколько недавно должен быть создан существующий расход,
# чтобы считаться потенциальным дубликатом (в минутах).
